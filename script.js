// A data dos feriados segue o mesmo fuso exibido no cabeçalho da TV.
function obterDataAcademia(agora=new Date()){
    const partes = new Intl.DateTimeFormat("pt-BR",{
        timeZone:"America/Sao_Paulo",
        year:"numeric",
        month:"2-digit",
        day:"2-digit"
    }).formatToParts(agora);
    const valores = Object.fromEntries(partes.map(p=>[p.type,p.value]));
    return `${valores.year}-${valores.month}-${valores.day}`;
}

// Algoritmo de Meeus/Jones/Butcher para calcular a Páscoa a cada ano.
// Sexta-feira Santa acontece dois dias antes da Páscoa.
function dataSextaFeiraSanta(ano){
    const a = ano % 19;
    const b = Math.floor(ano / 100);
    const c = ano % 100;
    const d = Math.floor(b / 4);
    const e = b % 4;
    const f = Math.floor((b + 8) / 25);
    const g = Math.floor((b - f + 1) / 3);
    const h = (19 * a + b - d - g + 15) % 30;
    const i = Math.floor(c / 4);
    const k = c % 4;
    const l = (32 + 2 * e + 2 * i - h - k + 7 * 30) % 7;
    const m = Math.floor((a + 11 * h + 22 * l) / 451);
    const mes = Math.floor((h + l - 7 * m + 114) / 31);
    const dia = (h + l - 7 * m + 114) % 31 + 1;
    const data = new Date(Date.UTC(ano,mes - 1,dia));
    data.setUTCDate(data.getUTCDate() - 2);
    return data.toISOString().slice(0,10);
}

// Corpus Christi é 60 dias depois da Páscoa (62 dias depois da Sexta-feira Santa).
// Calcular no formato ISO e com UTC evita erros nas mudanças de ano/mês.
function dataCorpusChristi(ano){
    const sextaSanta = dataSextaFeiraSanta(ano);
    const data = new Date(`${sextaSanta}T12:00:00Z`);
    data.setUTCDate(data.getUTCDate() + 62);
    return data.toISOString().slice(0,10);
}

function ehFeriado(dataISO){
    // Feriados nacionais fixos do Brasil (MM-DD).
    const nacionais = new Set([
        "01-01", // Confraternização Universal
        "04-21", // Tiradentes
        "05-01", // Dia do Trabalho
        "09-07", // Independência do Brasil
        "10-12", // Nossa Senhora Aparecida
        "11-02", // Finados
        "11-15", // Proclamação da República
        "11-20", // Dia da Consciência Negra
        "12-25"  // Natal
    ]);

    // Feriados municipais de Aparecida de Goiânia (Lei Municipal 82/1973;
    // 11 de maio e 14 de novembro confirmados pela Prefeitura e pelo TJGO).
    const municipais = new Set([
        "05-11", // Aniversário da fundação de Aparecida de Goiânia
        "11-14"  // Emancipação política e administrativa
    ]);

    const ano = Number(dataISO.slice(0,4));
    const mesDia = dataISO.slice(5);

    // Feriados contemplados pela Lei estadual 20.756/2020, art. 269, II.
    // São datas de não expediente estadual: a empresa privada adota por opção.
    // Em 2026, decreto 10.935/2026 transferiu 26/07 para 20/07.
    // Em anos posteriores, verificar se o governo mudou o dia 26/07 novamente.
    const fundacaoGoias = ano === 2026 ? "2026-07-20" : `${ano}-07-26`;
    const estadual = CONFIG.considerarFeriadosEstaduais === true
        && (mesDia === "10-24" || dataISO === fundacaoGoias);

    return nacionais.has(mesDia)
        || municipais.has(mesDia)
        || dataISO === dataSextaFeiraSanta(ano)
        || dataISO === dataCorpusChristi(ano)
        || estadual
        || CONFIG.feriadosExtras.some(data=>data === dataISO || data === mesDia);
}

function horarioAcademia(dia,dataISO=obterDataAcademia()){
    const feriado = ehFeriado(dataISO);
    const especial = CONFIG.horariosEspeciais[dataISO];
    if(especial) return {...especial,feriado};

    // Em feriados, utiliza o mesmo horário do domingo, inclusive aos sábados.
    if(feriado) return {abre:8,fecha:14,texto:"08h às 14h",feriado:true};

    if(dia >= 1 && dia <= 5){
        return {abre:5,fecha:24,texto:"05h às 00h",feriado:false};
    }

    if(dia === 6){
        return {abre:7,fecha:17,texto:"07h às 17h",feriado:false};
    }

    return {abre:8,fecha:14,texto:"08h às 14h",feriado:false};
}

