const DURACAO_TRANSICAO_TEMA = 2500;
let coresTemaAtuais = null;
let quadroAnimacaoTema = null;

function escreverCoresTema(overlay,cores){
    const chaves = ["dark","main","soft","light"];
    cores.forEach((rgb,i)=>{
        const [r,g,b] = rgb;
        overlay.style.setProperty(`--tema-${chaves[i]}`,`rgb(${r},${g},${b})`);
        const rgbNome = i === 3 ? "--tema-rgb" : `--tema-${chaves[i]}-rgb`;
        overlay.style.setProperty(rgbNome,`${r},${g},${b}`);
    });
}

function aplicarTemaFuncionamento(cor){
    const overlay = document.querySelector(".overlay");
    const destino = PALETAS_TEMA[cor];
    if(!overlay || !destino || overlay.dataset.corFuncionamento === cor) return;

    if(quadroAnimacaoTema !== null && typeof window !== "undefined"){
        window.cancelAnimationFrame(quadroAnimacaoTema);
        quadroAnimacaoTema = null;
    }

    overlay.classList.remove("tema-verde","tema-amarelo","tema-laranja","tema-vermelho");
    overlay.classList.add(`tema-${cor}`);
    overlay.dataset.corFuncionamento = cor;

    const animaDisponivel = typeof window !== "undefined" &&
        typeof window.requestAnimationFrame === "function";
    const reduzirMovimento = animaDisponivel &&
        typeof window.matchMedia === "function" &&
        window.matchMedia("(prefers-reduced-motion: reduce)").matches;

    // Na primeira carga, aplica o estado correto imediatamente, sem piscar verde.
    if(!coresTemaAtuais || !animaDisponivel || reduzirMovimento){
        coresTemaAtuais = destino.map(rgb=>[...rgb]);
        escreverCoresTema(overlay,coresTemaAtuais);
        return;
    }

    const origem = coresTemaAtuais.map(rgb=>[...rgb]);
    let inicioAnimacao = null;

    function animarTema(instante){
        if(inicioAnimacao === null) inicioAnimacao = instante;
        const progresso = Math.min(1,(instante - inicioAnimacao)/DURACAO_TRANSICAO_TEMA);
        const suavizacao = progresso < .5
            ? 4 * progresso * progresso * progresso
            : 1 - Math.pow(-2 * progresso + 2,3)/2;

        coresTemaAtuais = origem.map((rgb,i)=>rgb.map((valor,j)=>
            Math.round(valor + (destino[i][j] - valor) * suavizacao)
        ));
        escreverCoresTema(overlay,coresTemaAtuais);

        if(progresso < 1){
            quadroAnimacaoTema = window.requestAnimationFrame(animarTema);
        }else{
            quadroAnimacaoTema = null;
        }
    }
    quadroAnimacaoTema = window.requestAnimationFrame(animarTema);
}

// Obtém a hora local da academia, mesmo se o dispositivo estiver em outro fuso.
function obterSegundosDiaAcademia(agora=new Date()){
    const partes = new Intl.DateTimeFormat("pt-BR",{
        timeZone:"America/Sao_Paulo",
        hourCycle:"h23",hour:"2-digit",minute:"2-digit",second:"2-digit"
    }).formatToParts(agora);
    const valores = Object.fromEntries(partes.map(p=>[p.type,p.value]));
    return Number(valores.hour)*3600 + Number(valores.minute)*60 + Number(valores.second);
}

// A abertura seguinte considera o próprio dia (antes de abrir), sábados,
// domingos, feriados locais/nacionais e horários excepcionais cadastrados.
function obterProximaAbertura(agora=new Date()){
    const dataISO = obterDataAcademia(agora);
    const segundosHoje = obterSegundosDiaAcademia(agora);
    const dataBase = new Date(`${dataISO}T12:00:00Z`);

    for(let acrescimo=0;acrescimo<=8;acrescimo++){
        const data = new Date(dataBase);
        data.setUTCDate(data.getUTCDate() + acrescimo);
        const dataCandidata = data.toISOString().slice(0,10);
        const dia = data.getUTCDay();
        const horario = horarioAcademia(dia,dataCandidata);
        if(acrescimo===0 && segundosHoje>=horario.abre*3600) continue;
        return {dia,abre:horario.abre,dataISO:dataCandidata};
    }
    return null;
}

